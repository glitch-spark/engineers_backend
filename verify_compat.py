"""Proves passlib's bcrypt scheme can verify hashes produced by bcryptjs.

The hash below was generated by Node.js bcryptjs@2.4.3 (the same version the
Next.js app uses today):

    node -e 'console.log(require("bcryptjs").hashSync("TestP@ssword123!", 10))'

If passlib verifies it, existing production users can log in against this
FastAPI backend without re-hashing their passwords (see ADR-0001).

Run from engineers_backend/ with the venv:

    .venv/Scripts/python.exe verify_compat.py
"""
from passlib.context import CryptContext

ctx = CryptContext(schemes=["bcrypt"], deprecated="auto")

KNOWN_PLAINTEXT = "TestP@ssword123!"
BCRYPTJS_HASH = "$2a$10$NOW7kT4MLxkyJybZ4gDBmeoY.VVhdVeVL9OQu6jyYViJRpF3G4QhW"


def main() -> int:
    print(f"hash prefix: {BCRYPTJS_HASH[:4]} (bcryptjs default)")
    print(f"hash:        {BCRYPTJS_HASH}")
    print()

    correct = ctx.verify(KNOWN_PLAINTEXT, BCRYPTJS_HASH)
    print(f"verify(correct password, bcryptjs hash): {correct}")

    wrong = ctx.verify("wrong password", BCRYPTJS_HASH)
    print(f"verify(wrong password,   bcryptjs hash): {wrong}")

    print()
    if correct is True and wrong is False:
        print("RESULT: passlib + bcrypt can verify bcryptjs hashes — OK")
        return 0
    print("RESULT: COMPAT FAILED")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
